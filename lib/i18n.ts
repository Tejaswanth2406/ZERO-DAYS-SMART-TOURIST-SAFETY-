type Translations = typeof translations.en;
// FIX: Export TranslationKey to be used in other files for strong typing of translation keys.
export type TranslationKey = keyof Translations;

// Fallback mechanism: if a key is missing in a language, it uses the English version.
const getTranslation = (lang: Language, key: TranslationKey): string => {
  const langTranslations = translations[lang] as Translations | undefined;
  if (langTranslations && langTranslations[key]) {
    return langTranslations[key];
  }
  // @ts-ignore
  if (translations.en[key]) {
    return translations.en[key];
  }
  return key;
};

export const t = (key: TranslationKey, lang: Language): string => {
  const translation = getTranslation(lang, key);
  return translation;
};
